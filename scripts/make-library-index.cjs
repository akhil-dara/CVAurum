/**
 * Rewrite src/data/library/index.ts from whatever sits in samples/.
 *
 * The index enumerates its imports rather than globbing: the build's own SEO
 * step compiles this module with esbuild for Node, where Vite's import.meta.glob
 * does not exist, and one list both sides can read is worth more than two ways
 * of finding the same files. `library.test.ts` fails if this has not been run.
 *
 *   node scripts/make-library-index.cjs
 */
const fs = require('fs')
const path = require('path')

const DIR = path.join(__dirname, '..', 'src', 'data', 'library')
const SAMPLES = path.join(DIR, 'samples')

const slugs = fs
  .readdirSync(SAMPLES)
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))
  .map((f) => f.replace(/\.ts$/, ''))
  .sort()

const ident = (slug) => 's_' + slug.replace(/[^a-zA-Z0-9]/g, '_')

const body = `import type { LibrarySample } from './types'
import { withShowcase } from './showcase'
${slugs.map((s) => `import ${ident(s)} from './samples/${s}'`).join('\n')}

/**
 * Every sample in the library, in slug order.
 *
 * Generated by scripts/make-library-index.cjs — add a file under samples/ and
 * run it again rather than editing this list by hand.
 */
export const LIBRARY: readonly LibrarySample[] = [
${slugs.map((s) => `  ${ident(s)},`).join('\n')}
].map(withShowcase)

/** One sample by its URL segment, or undefined when there is no such sample. */
export function getSample(slug: string | undefined): LibrarySample | undefined {
  return slug ? LIBRARY.find((s) => s.slug === slug) : undefined
}

/** Every slug, for the sitemap and the build's static pages. */
export function allSampleSlugs(): string[] {
  return LIBRARY.map((s) => s.slug)
}
`

fs.writeFileSync(path.join(DIR, 'index.ts'), body)

// The count as a plain literal. The landing page says it in a sentence and
// has no use for the collection behind it, and importing LIBRARY to call
// .length would pull all of it into the lightest page on the site.
fs.writeFileSync(
  path.join(DIR, 'count.ts'),
  `/**
 * How many examples the library holds.
 *
 * A literal, not LIBRARY.length: a page that only wants the number must not
 * pull a hundred résumés into its bundle. Generated by
 * scripts/make-library-index.cjs; library.test.ts fails if it drifts.
 */
export const SAMPLE_COUNT = ${slugs.length}
`
)

// Which examples are shown in each design, as plain data: a design's page
// links them, and importing LIBRARY there would ship a hundred résumés to a
// page that needs a list of names. Read from each sample file's own fields.
const field = (src, name) => {
  const m = src.match(new RegExp(`\\n  ${name}:\\s*(['"])((?:\\\\.|(?!\\1).)*)\\1`))
  return m ? m[2].replace(/\\(['"])/g, '$1') : null
}
const byTemplate = {}
for (const slug of slugs) {
  const src = fs.readFileSync(path.join(DIR, 'samples', `${slug}.ts`), 'utf8')
  const template = field(src, 'template')
  const role = field(src, 'role')
  if (!template || !role) throw new Error(`${slug}: no template or role found`)
  ;(byTemplate[template] ??= []).push({ slug, role })
}
fs.writeFileSync(
  path.join(DIR, 'byTemplate.ts'),
  `/**
 * The examples shown in each design, by template id: slug and role only.
 *
 * Plain data so a design's page can link its examples without importing the
 * library. Generated by scripts/make-library-index.cjs; library.test.ts
 * fails if it drifts from the samples.
 */
export const EXAMPLES_BY_TEMPLATE: Record<string, { slug: string; role: string }[]> = ${JSON.stringify(byTemplate, null, 2)}
`
)

console.log(`library index: ${slugs.length} samples`)
