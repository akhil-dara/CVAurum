export const FOLIO_ICON_KINDS = Object.keys(GLYPHS) as FolioIconKind[]

type Glyph = { viewBox: string; pieces: Piece[] }

/** Move every coordinate of an absolute-command path by (-dx, -dy). The
 *  table only ever uses M, L, C and z (checked by folioIcons.test.ts), and
 *  each of those consumes whole x,y pairs, so number parity alone says which
 *  axis a token is on. Values are kept to the table's own tenth precision. */
function shiftPath(d: string, dx: number, dy: number): string {
  let i = 0
  return d.replace(/-?\d*\.?\d+/g, (n) => {
    const v = Number(n) - (i++ % 2 === 0 ? dx : dy)
    return String(Math.round(v * 10) / 10)
  })
}

/** The table is authored in its source coordinate space, where every
 *  viewBox has a non-zero origin. The PDF painter (walk.ts svgIconOps)
 *  refuses exactly that - a non-zero origin emits NO op, so the chip would
 *  paint as an empty square in every export while looking right on the
 *  canvas. Normalise once at load: subtract the origin from every
 *  coordinate and re-anchor the viewBox at 0 0. */
function normalise(g: Glyph): Glyph {
  const [x, y, w, h] = g.viewBox.trim().split(/[\s,]+/).map(Number)
  if (x === 0 && y === 0) return g
  return {
    viewBox: `0 0 ${w} ${h}`,
    pieces: g.pieces.map((p) => ({ k: p.k, d: shiftPath(p.d, x, y) })),
  }
}

const NORMALISED = Object.fromEntries(
  FOLIO_ICON_KINDS.map((k) => [k, normalise(GLYPHS[k])])
) as Record<FolioIconKind, Glyph>

/** The glyph as rendered: a zero-origin viewBox and paths shifted to match. */
export function folioGlyph(kind: FolioIconKind): Glyph {
  return NORMALISED[kind]
}

/** Which glyph a section key uses; unknown/custom sections fall back to
 *  the summary nib, the most neutral mark in the set. */
export function folioIconKind(sectionKey: string): FolioIconKind {
  const key = sectionKey.split(':')[0]
  return (Object.prototype.hasOwnProperty.call(GLYPHS, key) ? key : 'summary') as FolioIconKind
}

/** The svg class each kind of piece paints through; the fill lives in CSS on
 *  the <svg> root (artboard.css, .sicon-folio). */
const PIECE_CLASS: Record<Piece['k'], string> = {
  ink: 'rm-folio-ink',
  tint: 'rm-folio-tint',
  paper: 'rm-folio-paper',
}

/** Consecutive pieces of one kind, in table order. The PDF painter reads ONE
 *  fill per <svg> root (walk.ts svgIconOps) and ignores a fill attribute on
 *  a child, so a glyph whose pieces differ in colour has to be split into
 *  sibling <svg> elements. Splitting per RUN rather than per kind keeps the
 *  table's own stacking: a paper cut-out drawn between two ink pieces (the
 *  certificate seal, the reference portrait) must stay between them, or the
 *  ink drawn after it would be covered. Most glyphs are one to three svgs. */
function runs(pieces: Piece[]): Piece[][] {
  const out: Piece[][] = []
  for (const p of pieces) {
    const last = out[out.length - 1]
    if (last && last[0].k === p.k) last.push(p)
    else out.push([p])
  }
  return out
}

export function FolioIcon({ kind }: { kind: FolioIconKind }) {
  const g = folioGlyph(kind)
  return (
    <>
      {runs(g.pieces).map((run, i) => (
        <svg key={i} viewBox={g.viewBox} className={PIECE_CLASS[run[0].k]} aria-hidden focusable="false">
          {run.map((p, j) => (
            <path key={j} d={p.d} />
          ))}
        </svg>
      ))}
    </>
  )
}
